def candidate_starts(nx, block):
    f, tail = divmod(nx, block)
    starts = {0, min((2 + block - 1) // block, f - 1) * block, (f - 1) * block}
    if tail:
        starts.add(f * block)
    return sorted(starts)


def tile_terms(shape, mode, block, start, periodic_x, slabs=True):
    nx, ny, nz = shape
    b, p, d = min(block, nx-start), ny*nz, int(mode == "diagnostic")
    nin = nx*p if not slabs else ((b+4) if periodic_x else
          b + min(2, start) + min(2, nx-start-b)) * p
    nout = b*p
    objects = [8*nin, 40*b, 40*ny, 40*nz, (24+72*d)*nout, nout] + [4*nout]*3
    return sum(objects), objects


def memory_plan(shape, mode, periodic_x, block=None, threads=1, atom_bytes=0):
    nx, ny, nz = shape
    p, g, d = ny*nz, nx*ny*nz, int(mode == "diagnostic")
    b = nx if block is None else block
    starts = [0] if block is None else candidate_starts(nx, b)
    terms = [tile_terms(shape, mode, b, s, periodic_x, block is not None) for s in starts]
    w = max(t[0] for t in terms)
    common, acc = 65536 + 4096*threads, 65536
    host = 8*g + atom_bytes + 8192 + (25+72*d)*b*p + common + acc + w
    if block is not None:
        host += 8*(b+4)*p
    return dict(host_bytes=host, reader_atom_bytes=atom_bytes, device_array_bytes=w,
                host_fixed_common_bytes=common, host_fixed_openacc_bytes=acc,
                device_static_bytes=288, launch_parameter_bytes=272)


def check_plan(actual, expected):
    assert set(actual) == set(expected)
    assert all(type(value) is int and 0 <= value <= 2**63-1 for value in actual.values())
    assert actual == expected


def field_fixture(boundary):
    if boundary == "finite":
        return quadratic_fixture()
    result = fourier_fixture()
    result.periodic = (1, 1, 1) if boundary == "periodic" else (1, 0, 1)
    return result


def configure(path, card, backend="openacc", block=None):
    card["compute"]["backend"] = backend
    if block is None:
        card["compute"].update(layout="full_grid")
        card["compute"].pop("slab_planes", None)
    else:
        card["compute"].update(layout="x_slabs", slab_planes=block)
    write_card(path, card)


def add_atoms(cube, path, card, count=2):
    lines = cube.read_text(encoding="ascii").splitlines()
    header = lines[2].split()
    header[0] = str(count)
    lines[2] = " ".join(header)
    # Atom storage is charged, while the independent density is unchanged.
    lines[6:6] = ["1 1.0 0.125 -0.25 0.5"] * count
    cube.write_text("\n".join(lines)+"\n", encoding="ascii")
    card["input"].update(sha256=sha256(cube), bytes=cube.stat().st_size)
    write_card(path, card)


def worker_settings(shape, mode, budget):
    """Independent protocol-v1 NML, not generated by the candidate CLI."""
    fields = dict(protocol_version="1", shape=",".join(map(str, shape)), origin="0,0,0",
        step_vectors="1,0,0,0,1,0,0,0,1", periodic="0,0,0",
        endpoint_convention="'finite_nodes','finite_nodes','finite_nodes'",
        quantity="'electron_density'", spin_convention="'spin_summed'",
        density_representation="'all_electron'", length_unit="'bohr'",
        density_unit="'electron/bohr^3'", backend="1",
        output_mode=str(int(mode == "diagnostic")), rho_min="1e-12", negative_tolerance="0",
        omp_threads="1", memory_budget_bytes=str(budget), max_points=str(2**63-1))
    return "&nci_run\n" + "\n".join(f" {k}={v}," for k,v in fields.items()) + "\n/\n"


def run(executables, parent, cube, path, card, label, gpu=True):
    selected = dict(executables)
    selected["NCI_DRIVER"] = executables["NCI_OPENACC_DRIVER" if gpu else "NCI_DRIVER"]
    result, output = invoke(selected, parent, cube, path, output=parent / label)
    # Keep original worker logs in place. This extra test receipt binds every
    # invocation (including failures) for later independent per-process tracing.
    receipts = {}
    for name in ("stderr.log", "stdout.log", "build-info.stderr.log", "build-info.stdout.log",
                 "native.json", "manifest.json", "settings.nml"):
        p = output / name
        if p.is_file():
            receipts[name] = dict(path=str(p.resolve()), sha256=sha256(p), bytes=p.stat().st_size)
    evidence = dict(driver=str(selected["NCI_DRIVER"]), returncode=result.returncode,
                    output=str(output.resolve()), artifacts=receipts)
    (parent / (label + ".evidence.json")).write_text(json.dumps(evidence, indent=2)+"\n")
    if (output / "manifest.json").is_file():
        manifest = json_object(output / "manifest.json")
        binaries = manifest.get("binaries")
        assert binaries is None or isinstance(binaries, dict)
        driver = binaries.get("driver") if binaries is not None else None
        if driver is not None:
            assert Path(driver["path"]).resolve() == selected["NCI_DRIVER"].resolve()
    return result, output


def successful(result, output, card, field, mode, gpu=True, atom_bytes=0):
    manifest = check_success(result, output, card, field, mode)
    capabilities = ["cpu", "openacc"] if gpu else ["cpu"]
    check_build_info(manifest["build"], capabilities)
    native = manifest["native"]
    if card["compute"]["backend"] == "openacc":
        assert native["backend"] == "openacc"
        expected = memory_plan(field.rho.shape, mode, bool(field.periodic[0]),
            card["compute"].get("slab_planes"), card["compute"]["omp_threads"], atom_bytes)
        check_plan(native["memory_plan"], expected)
        assert expected["host_bytes"] <= card["limits"]["memory_budget_bytes"]
    else:
        assert "memory_plan" not in native
        assert native.get("backend", "cpu") == "cpu"
    assert (output / "stderr.log").is_file()
    assert (output / "build-info.stderr.log").is_file()
    for name, record in manifest["outputs"].items():
        assert record["sha256"] == sha256(output / name)
        assert set(record) == {"sha256", "bytes", "dtype", "byte_order", "shape",
                               "component_order", "unit", "point_order", "storage_order"}
        assert record["dtype"] == ("uint8" if name == "flags.u8" else "float64")
        assert record["byte_order"] == "little" and record["point_order"] == "z_fastest"
        assert record["storage_order"] == "point_major"
        assert record["component_order"] == COMPONENTS[name] and record["unit"] == UNITS[name]
    assert Path(manifest["binaries"]["backend_library"]["path"]).resolve() == Path(manifest["build"]["backend_library"]).resolve()
    for record in manifest["binaries"].values():
        binary = Path(record["path"])
        assert record["sha256"] == sha256(binary)
        assert record["bytes"] == binary.stat().st_size
    return manifest


def same_build_fields(a, b, names):
    for name in names:
        # Exact file bytes additionally cover NaN masks and their serialization.
        assert (a/name).read_bytes() == (b/name).read_bytes(), name


def cpu_gpu_fields(cpu, gpu, names, field):
    for name in names:
        if name == "flags.u8":
            a, b = (np.fromfile(p/name, dtype="u1") for p in (cpu, gpu))
            # Bit5 is a backend-local numerical uncertainty label. Each result
            # already satisfies the original flag/stat contract independently.
            assert_array_equal(a & 223, b & 223)
            continue
        a, b = (np.fromfile(p/name, dtype="<f8") for p in (cpu, gpu))
        assert_array_equal(np.isnan(a), np.isnan(b))
        valid = np.isfinite(a)
        if name == "signedrho.f64":
            mask, (_, _, eigen) = field.numerical_reference()
            stable = np.zeros(mask.shape, dtype=bool)
            stable[mask] = np.abs(eigen) > 1e-9
            assert_array_equal(b[stable.ravel()], a[stable.ravel()])
            continue
        atol, rtol = ((1e-11, 1e-9) if name == "rdg.f64" else (1e-12, 1e-10))
        assert_allclose(b[valid], a[valid], atol=atol, rtol=rtol)
